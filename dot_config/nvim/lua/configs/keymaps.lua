-- キーマップ。
--
-- ここに置くのは Neovim 自体のキー設定だけにする。プラグイン固有のキーは
-- lua/plugins/<プラグイン>.lua 側に書く(プラグインを外したらキーも一緒に消えるように)。
--
-- リーダーキーはマッピングを定義するより前に決めておく必要がある。マッピングは定義時点の
-- mapleader を展開して覚えるので、後から変えても定義済みのものは変わらない。
-- init.lua が configs を plugins より先に読むので、ここで設定すれば間に合う。
--
-- スペースにすると、ノーマルモードでの本来の動き(カーソルを右へ 1 文字)は失われる。
-- l があるので困らない。
vim.g.mapleader = " "

-- maplocalleader は設定しない。既定の "\" のままにして、リーダーと衝突させない。
